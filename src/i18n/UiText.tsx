export function translateUiText(s: string,
  en: boolean) {
  const lead = s.match(/^\s*/)?.[0] || "", trail = s.match(/\s*$/)?.[0] || "", core = s.trim().replace(/\s+/g, " ");
  if (!core)
    return s;
  if (!en)
    return s;
  let out = exact[core] || core;
  for (const [re, to] of esPatterns)
    out = out.replace(re, to);
  return lead + out + trail;
}
export function UiText({ text }: {
  text: string;
}) {
  const { en } = usePublicLanguage();
  return <>{translateUiText(text, en)}</>;
}
export function useUiText() {
  const { en } = usePublicLanguage();
  return useCallback((text: string) => translateUiText(text, en), [en]);
}
